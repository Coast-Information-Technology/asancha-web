export function getReservationStatusLabel(
    status: ReservationStatus,
): string {
    return (
        RESERVATION_STATUS_OPTIONS.find(
            (option) => option.value === status,
        )?.label ?? status
    );
}

export function getReservationPaymentStatusLabel(
    status: ReservationPaymentStatus,
): string {
    return (
        RESERVATION_PAYMENT_STATUS_OPTIONS.find(
            (option) => option.value === status,
        )?.label ?? status
    );
}
