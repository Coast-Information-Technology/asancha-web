/**
 * Asancha Reservation Constants
 *
 * Purpose:
 * Defines current-user reservation endpoints, routes, lifecycle labels,
 * default filters, pagination values, and safe user-facing messages.
 *
 * Responsibilities:
 * - Keep reservation API paths in one place.
 * - Define reservation and payment status options.
 * - Provide reservation, payment, listing, and deal-pack routes.
 * - Provide default filter state.
 * - Provide safe lifecycle and locked-action messages.
 *
 * Security notes:
 * - Admin confirmation, rejection, expiry, and forced cancellation endpoints
 *   must not appear here.
 * - Frontend constants do not grant permission to reserve or cancel.
 * - Reservation payment references must be generated by the backend.
 */

